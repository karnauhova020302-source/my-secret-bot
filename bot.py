# === ФУНКЦИИ ДЛЯ ХРАНЕНИЯ CHAT_ID ===
def save_chat_id(chat_id: int):
    with open(CHAT_ID_FILE, "w") as f:
        json.dump({"chat_id": chat_id}, f)

def load_chat_id():
    if os.path.exists(CHAT_ID_FILE):
        with open(CHAT_ID_FILE) as f:
            data = json.load(f)
            return data.get("chat_id")
    return None

# === ЗАГРУЗКА СОХРАНЁННОГО CHAT_ID ПРИ СТАРТЕ ===
target_chat_id = load_chat_id()  # теперь переменная хранит актуальный ID

