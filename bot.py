# === ЕЖЕДНЕВНАЯ ОТПРАВКА ===
async def send_daily(context: ContextTypes.DEFAULT_TYPE):
    global target_chat_id
    # Если ещё нет chat_id (никто не запускал), пробуем загрузить из файла
    if target_chat_id is None:
        target_chat_id = load_chat_id()
    if target_chat_id is None:
        return  # всё ещё нет — выходим

    choice = random.randint(1, 3)

    if choice == 1:
        await context.bot.send_message(chat_id=target_chat_id, text=random.choice(wishes))
    elif choice == 2:
        img_path = random.choice(images)
        try:
            if not os.path.exists(img_path):
                raise FileNotFoundError(f"Файл не найден: {img_path}")
            with open(img_path, "rb") as photo:
                await context.bot.send_photo(
                    chat_id=target_chat_id,
                    photo=photo,
                    caption=f"{FRIEND_NAME}, хорошего тебе дня ☀️"
                )
        except Exception as e:
            print(f"Ошибка при отправке фото: {e}")
            await context.bot.send_message(
                chat_id=target_chat_id,
                text=f"{FRIEND_NAME}, сегодня без картинки, но с тёплым пожеланием ☀️\n\n{random.choice(wishes)}"
            )
    else:
        await context.bot.send_message(chat_id=target_chat_id, text=random.choice(surprises))

# === ГЛАВНАЯ ФУНКЦИЯ ===
def main():
    app = Application.builder().token(TOKEN).build()

    # Добавляем команду /start
    app.add_handler(CommandHandler("start", start))

    # Настройка ежедневной задачи
    job_queue = app.job_queue
    if job_queue is not None:
        try:
            import pytz
            tz = pytz.timezone("Europe/Moscow")
        except ImportError:
            print("pytz не установлен, используется UTC.")
            tz = None

        # Отправка каждый день в 5:00 по Москве
        job_queue.run_daily(
            send_daily,
            time=datetime.time(hour=5, minute=0, second=0, tzinfo=tz)
        )
        print("Расписание установлено на 5:00 (Москва).")
    else:
        print("JobQueue не доступна. Установите APScheduler.")

    print("Бот запущен.")
    app.run_polling()

if __name__ == "__main__":
    main()